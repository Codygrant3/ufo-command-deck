/**
 * Merge external data sources into UFO_DATA
 * Called when the page loads
 */
function mergeExternalDataSources() {
    // Check if Wikipedia cases are loaded
    if (typeof WIKIPEDIA_CASES !== 'undefined' && Array.isArray(WIKIPEDIA_CASES)) {
        // Filter out duplicates (by checking if ID already exists)
        const existingIds = new Set(UFO_DATA.cases.map(c => c.id));
        const newWikipediaCases = WIKIPEDIA_CASES.filter(c => !existingIds.has(c.id));

        console.log(`📚 Loading ${newWikipediaCases.length} Wikipedia cases...`);
        UFO_DATA.cases.push(...newWikipediaCases);
    }

    // Check if NUFORC cases are loaded
    if (typeof NUFORC_CASES !== 'undefined' && Array.isArray(NUFORC_CASES)) {
        // Filter out duplicates
        const existingIds = new Set(UFO_DATA.cases.map(c => c.id));
        const newNuforcCases = NUFORC_CASES.filter(c => !existingIds.has(c.id));

        console.log(`📡 Loading ${newNuforcCases.length} NUFORC cases...`);
        UFO_DATA.cases.push(...newNuforcCases);
    }

    console.log(`🛸 Total cases loaded: ${UFO_DATA.cases.length}`);
}

